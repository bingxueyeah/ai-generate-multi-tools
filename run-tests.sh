#!/bin/bash
# Linux/Mac shell脚本 - 运行自动化测试

echo "============================================================"
echo "HTML工具生成器 - 自动化测试运行脚本"
echo "============================================================"
echo ""

# 检查Maven是否安装
if ! command -v mvn &> /dev/null; then
    echo "错误: 未找到Maven，请先安装Maven并添加到PATH"
    exit 1
fi

echo "正在运行测试..."
echo ""

# 运行Maven测试
mvn test

if [ $? -eq 0 ]; then
    echo ""
    echo "============================================================"
    echo "测试执行完成！"
    echo "============================================================"
else
    echo ""
    echo "============================================================"
    echo "测试执行失败！"
    echo "============================================================"
    exit 1
fi

